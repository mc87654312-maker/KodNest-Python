#int
a = 10
print(type(a),a)

#float
b = 10.45
print(type(b),b)

#bool
c = True
print(type(c),c)

#str
d = "Hello"
print(type(d),d)

#list
e = [1,2,3]
print(type(e),e)

#tuple
f = (1,2,3)
print(type(f),f)

#dict
g = {1: "Hello", 2: "world"}
print(type(g),g)

#set
h = {1,2,3}
print(type(h),h)

#complex
i = 1+3j
print(type(i),i)

#None

is_valid = None
print(type(is_valid),is_valid)
